let LANG = localStorage.getItem("cp_lang") || ((navigator.language || "").toLowerCase().startsWith("en") ? "en" : "zh");
function t(key) {
  const l = I18N[LANG] || I18N.zh;
  return (key in l ? l[key] : (key in I18N.zh ? I18N.zh[key] : key));
}
function setLang(l) {
  if (!I18N[l]) return;
  LANG = l;
  localStorage.setItem("cp_lang", l);
  applyI18n(document);
  if (typeof rerender === "function") rerender();
}
function applyI18n(root) {
  (root || document).querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.getAttribute("data-i18n")); });
  (root || document).querySelectorAll("[data-i18n-ph]").forEach((el) => { el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph"))); });
  (root || document).querySelectorAll("[data-i18n-title]").forEach((el) => { el.setAttribute("title", t(el.getAttribute("data-i18n-title"))); });
  (root || document).querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria"))); });
}
