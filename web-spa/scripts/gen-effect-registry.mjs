#!/usr/bin/env node
// Regenerates src/engine/effects/registry.generated.js by scanning the effects
// tree. "Directory is the registry": every effect owns its own directory, so N
// parallel authors never touch a shared list and never produce a merge conflict.
//
// Two depths are supported on purpose:
//   effects/<id>/effect.js              -- the P3 reference effect
//   effects/<category>/<id>/effect.js   -- P4 category fan-out
//
// The generator is also a gate. A directory that looks like an effect but has no
// effect.js is an error, not something to skip: silently dropping it would let an
// effect exist on disk, be absent from the registry, and never render -- with every
// check still green. That failure mode (an instrument passing because it never
// looked) already cost this repo a 19px overflow that survived on 28 routes.
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const effectsDir = path.join(root, 'src', 'engine', 'effects');
const outFile = path.join(effectsDir, 'registry.generated.js');
const GENERATED_BASENAME = 'registry.generated.js';

function dirsIn(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
}

function hasEffect(dir) {
  return fs.existsSync(path.join(dir, 'effect.js'));
}

const entries = [];
const problems = [];

for (const first of dirsIn(effectsDir)) {
  const firstPath = path.join(effectsDir, first);
  if (hasEffect(firstPath)) {
    entries.push({ id: first, specifier: `./${first}/effect.js` });
    continue;
  }
  const children = dirsIn(firstPath);
  if (children.length === 0) {
    problems.push(`${first}/ 既没有 effect.js 也没有子目录（空的特效目录）`);
    continue;
  }
  for (const second of children) {
    const secondPath = path.join(firstPath, second);
    if (!hasEffect(secondPath)) {
      problems.push(`${first}/${second}/ 缺少 effect.js`);
      continue;
    }
    entries.push({ id: second, specifier: `./${first}/${second}/effect.js` });
  }
}

const byId = new Map();
for (const entry of entries) {
  if (byId.has(entry.id)) problems.push(`特效 id 重复: ${entry.id} (${byId.get(entry.id)} 与 ${entry.specifier})`);
  else byId.set(entry.id, entry.specifier);
}

// The denominator is printed unconditionally. "Scanned 0" and "all fine" must
// never look the same in this output.
console.log(`effect registry: 扫描到 ${entries.length} 个特效，${problems.length} 个问题`);

if (problems.length) {
  for (const problem of problems) console.error(`  FAIL ${problem}`);
  process.exit(1);
}
if (entries.length === 0) {
  console.error('  FAIL 没有扫描到任何特效——registry 会是空的，这一定是配置错了');
  process.exit(1);
}

const sorted = [...byId.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const lines = sorted.map(([id, specifier]) => `  '${id}': () => import('${specifier}'),`);
const body = `/*
 * GENERATED by scripts/${path.basename(new URL(import.meta.url).pathname)}. Do not hand-edit this file:
 * each effect directory owns its own effect.js and the generator rebuilds this
 * registry in deterministic lexical order.
 */

export const effectLoaders = Object.freeze({
${lines.join('\n')}
});

export const effectIds = Object.freeze(Object.keys(effectLoaders));
`;

const previous = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
if (process.argv.includes('--check')) {
  if (previous !== body) {
    console.error('  FAIL registry.generated.js 与特效目录不同步，请运行 node scripts/gen-effect-registry.mjs');
    process.exit(1);
  }
  console.log(`effect registry: 与目录同步 (${sorted.length} 个)`);
} else {
  fs.writeFileSync(outFile, body);
  console.log(`effect registry: 已写入 ${GENERATED_BASENAME} (${sorted.length} 个)`);
}
